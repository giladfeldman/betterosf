/**
 * RO-Crate metadata for an exported project.
 *
 * BagIt says "these bytes are intact". RO-Crate says "this was a research project, here
 * are its authors, its licence, its wiki pages, and what each file is". A bag without it
 * is a pile of files; a crate without a bag has no arithmetic. The export writes both.
 *
 * RO-Crate 1.1 is JSON-LD over schema.org, which is what makes it readable by tools
 * nobody has written yet — the relevant property when the archive has to outlive the
 * platform it came from.
 *
 * Pure: takes facts, returns an object. No I/O, no clock.
 */

import type { ContributorView } from "@/lib/osf/contributors";

export const RO_CRATE_CONTEXT = "https://w3id.org/ro/crate/1.1/context";

export type CrateFile = {
  /** Path relative to the crate root, matching the bag's `data/` layout. */
  path: string;
  size: number;
  sha256?: string | null;
  contentType?: string | null;
  /** Recorded honestly so a reader knows which files were never checksum-checked. */
  verification?: "verified" | "unverifiable" | "failed";
};

export type CrateInput = {
  projectGuid: string;
  title: string;
  description: string;
  osfUrl: string;
  doi: string | null;
  datePublished: string;
  dateModified: string;
  keywords: string[];
  license: { name: string; url: string | null } | null;
  contributors: ContributorView[];
  files: CrateFile[];
  wikiPages: { name: string; path: string }[];
  appVersion: string;
  createdAt: string;
};

type JsonLdEntity = Record<string, unknown>;

/**
 * Build `ro-crate-metadata.json`.
 *
 * Contributors become `author` entries with an ORCID `@id` where — and only where — OSF
 * reported the ORCID as VERIFIED. An unverified identifier would be a claim about a real
 * person that neither we nor OSF can stand behind, so those people appear by name with
 * their ORCID status noted in `description` instead.
 */
export function buildRoCrate(input: CrateInput): { "@context": string; "@graph": JsonLdEntity[] } {
  const graph: JsonLdEntity[] = [];

  graph.push({
    "@type": "CreativeWork",
    "@id": "ro-crate-metadata.json",
    conformsTo: { "@id": "https://w3id.org/ro/crate/1.1" },
    about: { "@id": "./" },
    description: `Generated by BetterOSF ${input.appVersion} on ${input.createdAt}.`,
  });

  const authors = input.contributors.filter((c) => c.bibliographic);
  const authorRefs = authors.map((c) => ({ "@id": personId(c) }));

  const root: JsonLdEntity = {
    "@type": "Dataset",
    "@id": "./",
    name: input.title,
    description: input.description,
    datePublished: input.datePublished,
    dateModified: input.dateModified,
    identifier: input.doi ? `https://doi.org/${input.doi}` : input.osfUrl,
    url: input.osfUrl,
    author: authorRefs,
    hasPart: input.files.map((f) => ({ "@id": encodeCrateId(f.path) })),
  };
  if (input.keywords.length > 0) root.keywords = input.keywords;
  if (input.license) root.license = { "@id": input.license.url ?? input.license.name };
  graph.push(root);

  for (const c of authors) {
    const person: JsonLdEntity = { "@type": "Person", "@id": personId(c), name: c.fullName };
    if (c.givenName) person.givenName = c.givenName;
    if (c.familyName) person.familyName = c.familyName;
    if (!c.orcid && c.orcidStatus) {
      // Say why the identifier is absent rather than leaving a silent gap.
      person.description = `OSF holds an ORCID for this person with status "${c.orcidStatus}", which is not verified, so it is not asserted here.`;
    }
    if (c.unregistered) {
      person.description = "Listed on OSF as an unregistered contributor.";
    }
    graph.push(person);
  }

  // Non-bibliographic contributors are recorded too — they are part of the project's
  // history even though they are not authors, and DataCite has nowhere to put them.
  for (const c of input.contributors.filter((c) => !c.bibliographic)) {
    graph.push({
      "@type": "Person",
      "@id": personId(c),
      name: c.fullName,
      description: `Non-bibliographic contributor on OSF (permission: ${c.permission}).`,
    });
  }

  if (input.license) {
    graph.push({
      "@type": "CreativeWork",
      "@id": input.license.url ?? input.license.name,
      name: input.license.name,
    });
  }

  for (const f of input.files) {
    const entity: JsonLdEntity = {
      "@type": "File",
      "@id": encodeCrateId(f.path),
      name: f.path.split("/").pop() ?? f.path,
      contentSize: String(f.size),
    };
    if (f.contentType) entity.encodingFormat = f.contentType;
    if (f.sha256) entity.sha256 = f.sha256;
    if (f.verification && f.verification !== "verified") {
      entity.description =
        f.verification === "unverifiable"
          ? "OSF supplied no checksum for this file, so its fidelity to the original was not confirmed."
          : "This file FAILED verification during export. Do not rely on it.";
    }
    graph.push(entity);
  }

  for (const w of input.wikiPages) {
    graph.push({
      "@type": ["File", "CreativeWork"],
      "@id": encodeCrateId(w.path),
      name: w.name,
      encodingFormat: "text/markdown",
      description: `OSF wiki page "${w.name}". OSF provides no wiki export; this was retrieved through its API.`,
    });
  }

  return { "@context": RO_CRATE_CONTEXT, "@graph": graph };
}

function personId(c: ContributorView): string {
  // A verified ORCID is a globally resolvable identity and is by far the best @id.
  if (c.orcid) return `https://orcid.org/${c.orcid}`;
  if (c.userId) return `https://osf.io/${c.userId}/`;
  return `#contributor-${c.id}`;
}

/**
 * RO-Crate `@id`s are URI references, so a path with spaces or `#` must be encoded — but
 * the `/` separators must survive.
 */
export function encodeCrateId(path: string): string {
  return path.split("/").map(encodeURIComponent).join("/");
}
